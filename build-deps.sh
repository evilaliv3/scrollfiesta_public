#!/usr/bin/env bash
#
# build-deps.sh -- Build the vendored C/C++ dependencies for ScrollFiesta (Linux).
#
# Linux analog of build-deps.ps1. Produces the three static libraries that
# src/Makefile links from deps/lib/:
#
#     deps/lib/libtriangle.a    (Shewchuk's Triangle CDT, compiled from source)
#     deps/lib/libClipper2.a    (Clipper2 polygon boolean ops)
#     deps/lib/libClipper2Z.a   (Clipper2 with the Z coordinate, USINGZ)
#
# libtiff is built here from the sources already vendored in deps/src/tiff-4.7.1,
# the same ones build-deps.ps1 uses on Windows, and staged into deps/lib and
# deps/include. Before this it was the one dependency the Linux build could not
# satisfy on its own: the script asked for `sudo apt-get install libtiff-dev`,
# so a machine without root could not build ScrollFiesta at all even though the
# sources were sitting in the tree. If a system libtiff is preferred, set
#
#     SF_SYSTEM_TIFF=1 ./build-deps.sh
#
# and the vendored build is skipped.
#
# Run this ONCE before building the binaries:
#
#     ./build-deps.sh
#     cd src && make release -j"$(nproc)"
#
# Requires: gcc, g++, cmake (>= 3.24), make, ar.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
deps="$root/deps/src"
lib="$root/deps/lib"
jobs="$(nproc 2>/dev/null || echo 4)"

mkdir -p "$lib"

cyan() { printf '\033[36m==> %s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }

# --- Triangle ---------------------------------------------------------------
# Shewchuk's Triangle. The Windows build (cube_mesh.vcxproj / grid_weld.vcxproj)
# compiles triangle.c directly with these exact defines at WarningLevel1:
#   TRILIBRARY  -- build as a callable library (no main())
#   ANSI_DECLARATORS, NO_TIMER, REAL=double, VOID=int
# It is third-party numerical code, so suppress warnings (-w) the same way the
# .vcxproj drops it to the lowest warning level. NO_TIMER avoids the <sys/time.h>
# timing path; we deliberately do NOT define LINUX (no x87 FPU control word).
cyan "libtriangle.a"
tri_obj="$(mktemp -d)/triangle.o"
gcc -O2 -w \
    -DTRILIBRARY -DANSI_DECLARATORS -DNO_TIMER -DREAL=double -DVOID=int \
    -c "$deps/triangle/triangle.c" -o "$tri_obj"
ar rcs "$lib/libtriangle.a" "$tri_obj"
rm -rf "$(dirname "$tri_obj")"
echo "    staged libtriangle.a"

# --- Clipper2 ---------------------------------------------------------------
# CMake build of the static Clipper2 / Clipper2Z libraries. Tests git-clone
# googletest, so keep them off (as build-deps.ps1 does). Clipper2's CMakeLists
# hard-codes -Werror for non-MSVC; it is warning-clean under GCC 13, but pass
# -DCMAKE_COMPILE_WARNING_AS_ERROR=OFF as a cheap safety net for newer compilers.
cyan "libClipper2.a + libClipper2Z.a"
clipper_src="$deps/Clipper2/CPP"
clipper_bld="$clipper_src/build"
cmake -S "$clipper_src" -B "$clipper_bld" \
    -DCLIPPER2_TESTS=OFF -DCLIPPER2_EXAMPLES=OFF -DCLIPPER2_UTILS=OFF \
    -DBUILD_SHARED_LIBS=OFF -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_COMPILE_WARNING_AS_ERROR=OFF
cmake --build "$clipper_bld" --config Release -j"$jobs"

# Stage the two .a's (CMake names them libClipper2.a / libClipper2Z.a on Linux).
for name in libClipper2.a libClipper2Z.a; do
    found="$(find "$clipper_bld" -name "$name" -print -quit)"
    if [ -z "$found" ]; then
        echo "ERROR: $name not produced by the Clipper2 build" >&2
        exit 1
    fi
    cp -f "$found" "$lib/"
    echo "    staged $name"
done

# --- libtiff ----------------------------------------------------------------
# Mirrors the libtiff section of build-deps.ps1, which builds the very same
# vendored tree. Tools, tests and contrib are off: only the library is linked.
if [ "${SF_SYSTEM_TIFF:-0}" = "1" ]; then
    cyan "libtiff: skipped, SF_SYSTEM_TIFF=1 (linking the system libtiff)"
else
    cyan "libtiff.a"
    tiff_src="$deps/tiff-4.7.1"
    tiff_bld="$tiff_src/bld"
    inc="$root/deps/include"
    mkdir -p "$inc"
    cmake -S "$tiff_src" -B "$tiff_bld" \
        -DBUILD_SHARED_LIBS=OFF -Dtiff-tools=OFF -Dtiff-tests=OFF \
        -Dtiff-contrib=OFF -Dtiff-docs=OFF -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_COMPILE_WARNING_AS_ERROR=OFF
    cmake --build "$tiff_bld" --config Release -j"$jobs"
    found="$(find "$tiff_bld" -name libtiff.a -print -quit)"
    if [ -z "$found" ]; then
        echo "ERROR: libtiff.a not produced by the libtiff build" >&2
        exit 1
    fi
    cp -f "$found" "$lib/"
    # tiffconf.h and tiffvers.h are generated by the configure step, so they
    # live in the build tree, not beside the checked-in headers.
    cp -f "$tiff_src/libtiff/tiff.h" "$tiff_src/libtiff/tiffio.h" "$inc/"
    cp -f "$tiff_bld/libtiff/tiffconf.h" "$tiff_bld/libtiff/tiffvers.h" "$inc/" 2>/dev/null || true
    # Which system libraries the static libtiff needs depends on which codecs
    # CMake found: guessing here is how a link breaks on the next machine. Ask
    # the archive itself and write the answer where the Makefile can read it.
    : > "$lib/tiff.flags"
    # Read the symbol table once, then match it in the shell. `nm ... | grep -q` looks equivalent
    # and is not: grep exits at the first match, nm dies of SIGPIPE, and under this script's own
    # `set -o pipefail` the test then reads as false. Whether it does is a race between the two
    # processes, so the flags file comes out right on one machine and empty on the next, and the
    # link fails with undefined zlib symbols that have nothing to do with the real problem.
    tiff_syms="$(nm -u "$lib/libtiff.a" 2>/dev/null || true)"
    for sym_lib in "deflate:-lz" "jpeg_std_error:-ljpeg" "LZ4_compress_default:-llz4" \
                   "ZSTD_compress:-lzstd" "WebPGetInfo:-lwebp"; do
        sym="${sym_lib%%:*}"; flag="${sym_lib##*:}"
        if grep -q "\b$sym\b" <<< "$tiff_syms"; then
            printf ' %s' "$flag" >> "$lib/tiff.flags"
        fi
    done
    echo "    staged libtiff.a and its headers into deps/ (needs:$(cat "$lib/tiff.flags"))"
fi

echo
green "All dependencies staged into $lib"
ls -l "$lib"
